import { z } from 'zod';
import { isSortKey } from './sort-key.js';

/*
 * 清单、收件箱、文件夹 (spec 用户故事 12–15) and 归档 (16). Every user has exactly one 收件箱;
 * it cannot be deleted, archived or edited. 文件夹 are one level deep and hold
 * only 清单. Sidebar order: 文件夹 and top-level 清单 share one sort-key space,
 * 清单 inside a 文件夹 have their own.
 */

export const INBOX_NAME = '收件箱';

/** Swatches offered by the colour picker (any #rrggbb is accepted). */
export const LIST_COLORS = [
  '#ff6161',
  '#ffac38',
  '#ffd324',
  '#e6ea49',
  '#35d870',
  '#4ca1ff',
  '#6e75f4',
  '#ad73ff',
  '#ff8ad8',
  '#9e9fa3',
] as const;

/** Icons offered by the icon picker; a 清单 icon is a short emoji or symbol. */
export const LIST_ICONS = ['📋', '📁', '💼', '🏠', '📚', '🛒', '💡', '🎯', '✈️', '💪', '🎵', '❤️'] as const;

export const sortKeySchema = z.string().refine(isSortKey, '排序键不合法');
export const entityNameSchema = z.string().trim().min(1, '名称不能为空').max(64, '名称最多 64 个字符');
export const colorSchema = z
  .string()
  .regex(/^#[0-9a-fA-F]{6}$/, '颜色必须是 #rrggbb')
  .transform((c) => c.toLowerCase());
export const iconSchema = z
  .string()
  .trim()
  .min(1)
  .max(16, '图标太长')
  .refine((s) => !/\s/.test(s), '图标不能包含空白');

const syncFields = {
  id: z.uuid(),
  createdAt: z.iso.datetime(),
  updatedAt: z.iso.datetime(),
  revision: z.number().int().nonnegative(),
};

export const folderSchema = z.object({
  ...syncFields,
  name: z.string(),
  sortOrder: z.string(),
  collapsed: z.boolean(),
});
export type Folder = z.infer<typeof folderSchema>;

export const listSchema = z.object({
  ...syncFields,
  name: z.string(),
  color: z.string().nullable(),
  icon: z.string().nullable(),
  folderId: z.uuid().nullable(),
  sortOrder: z.string(),
  isInbox: z.boolean(),
  /** 归档: set while archived (hidden from the sidebar tree, its tasks out of every 智能清单). */
  archivedAt: z.iso.datetime().nullable(),
  /** 不进智能清单 (spec 用户故事 17): its tasks stay out of every 智能清单 but are still searched and filtered. */
  excludeFromSmartLists: z.boolean(),
});
export type TaskList = z.infer<typeof listSchema>;

/** `GET /api/lists`: the 收件箱 first, then every 清单 (archived ones included, see `archivedAt`) and 文件夹 in sidebar order. */
export const sidebarResponseSchema = z.object({
  lists: z.array(listSchema),
  folders: z.array(folderSchema),
  /** Open tasks per 清单 id (清单 without open tasks are omitted). */
  openTaskCounts: z.record(z.string(), z.number().int().nonnegative()),
});
export type SidebarResponse = z.infer<typeof sidebarResponseSchema>;

export const createListRequestSchema = z.object({
  /** Client-generated id (ADR-0004); generated by the server when omitted. */
  id: z.uuid().optional(),
  name: entityNameSchema,
  color: colorSchema.nullable().optional(),
  icon: iconSchema.nullable().optional(),
  folderId: z.uuid().nullable().optional(),
  excludeFromSmartLists: z.boolean().optional(),
  /** Defaults to the end of its sidebar level. */
  sortOrder: sortKeySchema.optional(),
});
export type CreateListRequest = z.input<typeof createListRequestSchema>;

export const updateListRequestSchema = z
  .object({
    name: entityNameSchema,
    color: colorSchema.nullable(),
    icon: iconSchema.nullable(),
    folderId: z.uuid().nullable(),
    sortOrder: sortKeySchema,
    /** 归档 / 取消归档. */
    archived: z.boolean(),
    excludeFromSmartLists: z.boolean(),
  })
  .partial()
  .strict();
export type UpdateListRequest = z.input<typeof updateListRequestSchema>;

export const createFolderRequestSchema = z.object({
  id: z.uuid().optional(),
  name: entityNameSchema,
  sortOrder: sortKeySchema.optional(),
});
export type CreateFolderRequest = z.input<typeof createFolderRequestSchema>;

export const updateFolderRequestSchema = z
  .object({ name: entityNameSchema, collapsed: z.boolean(), sortOrder: sortKeySchema })
  .partial()
  .strict();
export type UpdateFolderRequest = z.input<typeof updateFolderRequestSchema>;
